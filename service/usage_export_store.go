package service

import (
	"errors"
	"io"
	"os"
	"path/filepath"
	"regexp"
)

// ExportStore reads and writes export files. Keys are generated by the server and are never
// paths supplied by clients.
type ExportStore interface {
	Put(key string, content io.Reader) (int64, error)
	Open(key string) (io.ReadCloser, error)
	Delete(key string) error
}

var errInvalidExportKey = errors.New("invalid export key")

// exportKeyPattern limits keys to file-name characters, so a key cannot leave the directory.
var exportKeyPattern = regexp.MustCompile(`^[A-Za-z0-9_-]{1,96}\.(csv|xlsx)$`)

// LocalDiskExportStore keeps export files in one directory. It only suits a single instance:
// other instances cannot read files written here.
type LocalDiskExportStore struct {
	dir string
}

func NewLocalDiskExportStore(dir string) *LocalDiskExportStore {
	return &LocalDiskExportStore{dir: dir}
}

func (store *LocalDiskExportStore) path(key string) (string, error) {
	if !exportKeyPattern.MatchString(key) {
		return "", errInvalidExportKey
	}
	return filepath.Join(store.dir, key), nil
}

// Put writes to a temporary file and renames it, so readers never see a partial file.
func (store *LocalDiskExportStore) Put(key string, content io.Reader) (int64, error) {
	target, err := store.path(key)
	if err != nil {
		return 0, err
	}
	if err := os.MkdirAll(store.dir, 0o700); err != nil {
		return 0, err
	}
	temp, err := os.CreateTemp(store.dir, ".export-*.tmp")
	if err != nil {
		return 0, err
	}
	written, copyErr := io.Copy(temp, content)
	closeErr := temp.Close()
	if copyErr == nil {
		copyErr = closeErr
	}
	if copyErr != nil {
		_ = os.Remove(temp.Name())
		return 0, copyErr
	}
	if err := os.Rename(temp.Name(), target); err != nil {
		_ = os.Remove(temp.Name())
		return 0, err
	}
	return written, nil
}

func (store *LocalDiskExportStore) Open(key string) (io.ReadCloser, error) {
	target, err := store.path(key)
	if err != nil {
		return nil, err
	}
	return os.Open(target)
}

// Delete removes a file. A missing file is not an error, so cleanup can be retried.
func (store *LocalDiskExportStore) Delete(key string) error {
	target, err := store.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(target); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}
